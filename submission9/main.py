# 8.Реалізувати програму для заміни всіх дат у форматі dd-mm-yyyy на yyyy-mm-dd.

import re

def transform_dates():
    """ Програма для переформатування дат """
    print("Введіть текст, що містить дати у форматі dd-mm-yyyy:")

    # Отримуємо вхідні дані
    text = input("> ")

    # Регулярний вираз:
    # (\d{2}) - група 1 (день)
    # (\d{2}) - група 2 (місяць)
    # (\d{4}) - група 3 (рік)
    date_pattern = r'(\d{2})-(\d{2})-(\d{4})'

    # Використовуємо re.sub для заміни
    # \3-\2-\1 міняє порядок груп на рік-місяць-день
    result = re.sub(date_pattern, r'\3-\2-\1', text)

    print("\nРезультат обробки:")
    print(result)


if __name__ == "__main__":
    transform_dates()